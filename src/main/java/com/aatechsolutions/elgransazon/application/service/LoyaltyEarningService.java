package com.aatechsolutions.elgransazon.application.service;

import com.aatechsolutions.elgransazon.domain.entity.*;
import com.aatechsolutions.elgransazon.domain.repository.LoyaltyStampEventRepository;
import com.aatechsolutions.elgransazon.domain.repository.OrderRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.Optional;

/**
 * Awards loyalty stamps when an order is paid.
 *
 * <p>Rules (all configurable in the loyalty program):</p>
 * <ul>
 *   <li>Only orders linked to a registered customer and paid in full count.</li>
 *   <li>The order must reach the minimum purchase amount and minimum item count.</li>
 *   <li>A reward order (total $0, generated by a redemption) never earns stamps.</li>
 *   <li>Each order earns at most once; the unique ledger constraint is the last line
 *       of defence against double payment callbacks.</li>
 *   <li>The optional daily cap counts stamps earned today in the company timezone.</li>
 * </ul>
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class LoyaltyEarningService {

    private final OrderRepository orderRepository;
    private final LoyaltyProgramService programService;
    private final LoyaltyCycleService cycleService;
    private final LoyaltyAccountService accountService;
    private final LoyaltyLedgerService ledgerService;
    private final LoyaltyStampEventRepository eventRepository;
    private final FeatureAccessService featureAccessService;
    private final DateTimeService dateTimeService;

    /**
     * @return true when a stamp event was written. Safe to call more than once;
     *         a second call for the same order is a no-op.
     */
    @Transactional
    public boolean awardForPaidOrder(Long orderId, String username) {
        Order order = orderRepository.findByIdWithDetails(orderId).orElse(null);
        if (order == null) {
            log.warn("Loyalty: paid order {} not found", orderId);
            return false;
        }

        Company company = order.getCompany();
        if (company == null || order.getCustomer() == null) {
            return false;
        }
        if (order.getStatus() != OrderStatus.PAID) {
            return false;
        }
        if (!featureAccessService.isEnabled(company, FeatureKey.LOYALTY)) {
            return false;
        }
        if (!cycleService.processAndCheck(company)) {
            log.info("Loyalty: stamp cycle for company {} has expired", company.getIdCompany());
            return false;
        }
        if (eventRepository.existsByOrder_IdOrderAndEventType(orderId, LoyaltyStampEventType.EARN)) {
            log.debug("Loyalty: order {} already earned stamps", orderId);
            return false;
        }

        // A pure reward order totals $0.00 and never earns stamps. A mixed bill
        // (paid items plus a free reward line) still earns for the paid part.
        BigDecimal orderTotal = order.getTotal() != null ? order.getTotal() : BigDecimal.ZERO;
        if (orderTotal.compareTo(BigDecimal.ZERO) <= 0) {
            return false;
        }

        Optional<LoyaltyProgram> programOpt = programService.findForCompany(company);
        if (programOpt.isEmpty() || !programOpt.get().isActive()) {
            return false;
        }
        LoyaltyProgram program = programOpt.get();

        int itemCount = order.getOrderDetails().stream()
                .filter(detail -> !detail.isComboChild())
                .mapToInt(detail -> detail.getQuantity() != null ? detail.getQuantity() : 0)
                .sum();

        if (program.hasMinimumPurchase()
                && orderTotal.compareTo(program.getMinimumPurchaseAmount()) < 0) {
            log.debug("Loyalty: order {} total {} below minimum {}", orderId, orderTotal,
                    program.getMinimumPurchaseAmount());
            return false;
        }
        if (program.hasMinimumItems() && itemCount < program.getMinimumItems()) {
            log.debug("Loyalty: order {} has {} items, minimum is {}", orderId, itemCount,
                    program.getMinimumItems());
            return false;
        }

        LoyaltyAccount account = accountService.getOrCreate(company, order.getCustomer());
        // Serialize concurrent awards for the same customer.
        account = accountService.lock(account.getId());

        int stamps = program.getMaxStampsPerSale() != null ? program.getMaxStampsPerSale() : 1;
        stamps = Math.max(1, Math.min(stamps, 10));

        if (program.getMaxStampsPerDay() != null && program.getMaxStampsPerDay() > 0) {
            LocalDateTime startOfDay = dateTimeService.startOfDayUtc(dateTimeService.todayLocal());
            long earnedToday = eventRepository.sumStampsSince(
                    account, LoyaltyStampEventType.EARN, startOfDay);
            if (earnedToday + stamps > program.getMaxStampsPerDay()) {
                log.debug("Loyalty: account {} reached daily cap of {} stamps",
                        account.getId(), program.getMaxStampsPerDay());
                return false;
            }
        }

        account.earn(stamps);
        accountService.save(account);
        ledgerService.record(company, account, order, null,
                LoyaltyStampEventType.EARN, stamps, account.safeBalance(),
                "Compra " + order.getOrderNumber(), username);

        log.info("Loyalty: awarded {} stamp(s) to customer {} for order {}",
                stamps, order.getCustomer().getIdCustomer(), order.getOrderNumber());
        return true;
    }
}
